class ai_settings {
    /**
     * Whether the AI assistant is turned on for the site. It is off until an administrator turns it on, because
     * it sends course content to the site's AI provider.
     *
     * @return bool
     */
    public static function enabled(): bool {
        return !empty(get_config('gradingform_matrix', 'enableai'));
    }
}
